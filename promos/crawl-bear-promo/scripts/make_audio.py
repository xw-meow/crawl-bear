# One chord per bar, 4-bar loop: C – G/B – Am – F.
# `tones` follows the brief's arpeggio order: ROOT, FIFTH, OCTAVE, THIRD.
CHORDS = [
    {"name": "C", "root": 48, "tones": [60, 67, 72, 64]},  # C3 | C4 G4 C5 E4
    {"name": "G/B", "root": 47, "tones": [59, 62, 67, 71]},  # B2 | B3 D4 G4 B4
    {"name": "Am", "root": 45, "tones": [57, 64, 69, 60]},  # A2 | A3 E4 A4 C4
    {"name": "F", "root": 41, "tones": [53, 60, 65, 57]},  # F2 | F3 C4 F4 A3
]

# Two alternating 8-eighth arpeggio contours: gentle up-and-back, never a scale.
ARPEGGIO_PATTERNS = [
    [0, 1, 2, 3, 2, 1, 2, 1],
    [0, 2, 1, 3, 2, 3, 1, 2],
]


def build_music() -> tuple[np.ndarray, dict[str, np.ndarray]]:
    """Render the 54 s music bed. Returns (stereo_mix, stem_dict)."""
    total = int(round(SR * MUSIC_DURATION))
    pluck_bus = np.zeros((2, total), dtype=np.float64)
    pad_bus = np.zeros((2, total), dtype=np.float64)
    shaker_bus = np.zeros((2, total), dtype=np.float64)
    lift_bus = np.zeros((2, total), dtype=np.float64)

    # Deterministic decision/velocity RNGs. Consumption order is fixed, so the
    # output is stable across runs.
    human = random.Random(20261103)
    noise_rng = np.random.default_rng(20261103)

    # Tone-index -> stereo placement. Narrow, sits around the centre so the bed
    # still folds down to mono cleanly.
    TONE_PAN = [-0.20, 0.12, 0.22, -0.09]

    bar_count = int(math.ceil(MUSIC_DURATION / BAR))
    for bar in range(bar_count):
        if bar * BAR >= MUSIC_DURATION:
            break
        chord = CHORDS[bar % 4]
        pattern = ARPEGGIO_PATTERNS[(bar // 2) % 2]
        bar_start = bar * BAR

        # --- marimba eighth-note arpeggio --------------------------------
        for eighth in range(8):
            # Occasional rests and a little swing are what stop the eighths
            # from reading as a metronome.
            if human.random() < 0.055:
                continue
            tone_index = pattern[eighth]
            midi = chord["tones"][tone_index]
            freq = midi_hz(midi)

            velocity = 0.52
            if eighth % 4 == 0:
                velocity *= 1.28  # beat 1 / beat 3 accent
            elif eighth % 2 == 1:
                velocity *= 0.84  # lighter off-beats
            velocity *= 0.90 + 0.20 * human.random()  # velocity humanising

            swing = 0.020 if eighth % 2 == 1 else 0.0
            jitter = (human.random() * 2.0 - 1.0) * 0.004

            note = marimba_note(freq, velocity)
            add_into(
                pluck_bus,
                note,
                bar_start + eighth * EIGHTH + swing + jitter,
                TONE_PAN[tone_index] + (human.random() * 2.0 - 1.0) * 0.03,
            )

        # --- bass pad (one per bar, overlapping into the next bar) -------
        pad = pad_note(midi_hz(chord["root"]), BAR + 0.55, 0.11)
        add_into(pad_bus, pad, bar_start, 0.0)

        # --- shaker eighths, extremely light ----------------------------
        for eighth in range(8):
            accented = 1.0 if eighth % 2 == 1 else 0.72
            amp = 0.030 * accented * (0.75 + 0.5 * human.random())
            hit = shaker_hit(noise_rng, amp)
            add_into(
                shaker_bus,
                hit,
                bar_start + eighth * EIGHTH + (human.random() * 2.0 - 1.0) * 0.003,
                (-0.30 if eighth % 2 else 0.26),
            )

        # --- bars 4–8 lift: one soft high bell per downbeat -------------
        # A gentle 1.4 s swell around bar 5 plus a sparse octave-up note keeps
        # the middle of the 54 s from feeling static.
        if 3 <= bar <= 7:
            lift_midi = chord["tones"][2] + 12
            lift = marimba_note(midi_hz(lift_midi), 0.16, ring=1.1)
            add_into(lift_bus, lift, bar_start, 0.16 if bar % 2 == 0 else -0.14)

    # --- gentle arrangement automation ---------------------------------
    n = total
    t = np.arange(n) / SR
    # Very slow "breathing" so the bed never sounds stamped: +/-0.3 dB.
    breathing = 1.0 + 0.035 * np.sin(2.0 * np.pi * t / 19.0 - 0.8)
    # The bars 4–8 lift: a ~1.4 s raised-cosine bump centred on bar 5, +0.6 dB.
    bump = np.exp(-0.5 * ((t - 12.5) / 0.62) ** 2)
    lift_gain = breathing * (1.0 + 0.07 * bump)

    mix = (pluck_bus + pad_bus + shaker_bus + lift_bus) * lift_gain

    # --- master chain ---------------------------------------------------
    mix = np.stack([lowpass(channel, 13500.0) for channel in mix])  # tame hiss
    mix -= np.mean(mix, axis=1, keepdims=True)  # remove DC
    fade_edges(mix, in_s=0.45, out_s=2.0)  # 2 s tail fade, per brief

    # RMS target first, then guarantee the peak ceiling.
    rms = float(np.sqrt(np.mean(mix**2)))
    mix *= db_to_amp(MUSIC_RMS_TARGET_DB) / max(rms, 1e-9)
    peak = float(np.max(np.abs(mix)))
    if peak > db_to_amp(MUSIC_PEAK_CEILING_DB):
        mix *= db_to_amp(MUSIC_PEAK_CEILING_DB) / peak

    stems = {
        "plucks": pluck_bus,
        "pad": pad_bus,
        "shaker": shaker_bus,
        "lift": lift_bus,
    }
    return mix, stems


