def make_pop() -> np.ndarray:
    """60 ms card pop: 1200 Hz sine, fast decay, tiny transient click."""
    rng = np.random.default_rng(11)
    n = int(SR * 0.060)
    t = np.arange(n) / SR
    tone = np.sin(2.0 * np.pi * 1200.0 * t) * np.exp(-t / 0.013)
    attack = 1.0 - np.exp(-t / 0.0008)
    click = rng.standard_normal(n) * np.exp(-t / 0.0011) * 0.22
    wave_ = (tone * attack + click) * 0.9
    return fade_edges(wave_, 0.0005, 0.008)


def make_click() -> np.ndarray:
    """40 ms UI click: 800 Hz blip plus a short noise transient."""
    rng = np.random.default_rng(23)
    n = int(SR * 0.040)
    t = np.arange(n) / SR
    tone = np.sin(2.0 * np.pi * 800.0 * t) * np.exp(-t / 0.0085)
    transient = highpass(rng.standard_normal(n), 2200.0) * np.exp(-t / 0.0022) * 0.55
    wave_ = tone * (1.0 - np.exp(-t / 0.0006)) + transient
    return fade_edges(wave_, 0.0005, 0.006)


def make_stamp() -> np.ndarray:
    """220 ms rubber stamp: 90 Hz thump sweeping down + muffled noise body."""
    rng = np.random.default_rng(37)
    n = int(SR * 0.220)
    t = np.arange(n) / SR

    # Pitch drops 90 -> ~55 Hz quickly; that is the "cardboard + rubber" part.
    freq = 90.0 * np.exp(-t / 0.045) + 48.0 * (1.0 - np.exp(-t / 0.045))
    phase = 2.0 * np.pi * np.cumsum(freq) / SR
    thump = np.sin(phase) * np.exp(-t / 0.080)

    muffled = lowpass(rng.standard_normal(n), 620.0) * np.exp(-t / 0.042) * 0.85
    body = thump * 1.0 + muffled
    return fade_edges(body, 0.0008, 0.02)


def make_whoosh() -> np.ndarray:
    """380 ms transition swoosh: white noise band-passed 200 -> 3000 Hz."""
    rng = np.random.default_rng(41)
    n = int(SR * 0.380)
    t = np.arange(n) / SR
    noise = rng.standard_normal(n)

    # TPT state-variable filter with an exponential cutoff sweep. Written as a
    # plain loop because scipy is not available in this runtime; 16.7k samples
    # keeps it fast enough.
    q = 1.35
    ic1 = 0.0
    ic2 = 0.0
    filtered = np.empty(n, dtype=np.float64)
    for i in range(n):
        frac = i / (n - 1)
        cutoff = math.exp(
            math.log(200.0) * (1.0 - frac) + math.log(3000.0) * frac
        )
        g = math.tan(math.pi * cutoff / SR)
        a1 = 1.0 / (1.0 + g * (g + 1.0 / q))
        a2 = g * a1
        a3 = g * a2
        v3 = noise[i] - ic2
        v1 = a1 * ic1 + a2 * v3
        v2 = ic2 + a2 * ic1 + a3 * v3
        ic1 = 2.0 * v1 - ic1
        ic2 = 2.0 * v2 - ic2
        filtered[i] = v1

    # Bell-shaped amplitude: quick 60 ms fade in, ~200 ms fade out.
    env = smoothstep(t / 0.060) * (1.0 - smoothstep((t - 0.180) / 0.200))
    env *= 0.72 + 0.28 * np.sin(np.pi * t / 0.380)
    wave_ = filtered * env
    return fade_edges(wave_, 0.0005, 0.012)


def make_chime() -> np.ndarray:
    """900 ms success bell: C6 + E6 sines with exponential decay."""
    n = int(SR * 0.900)
    t = np.arange(n) / SR
    c6 = midi_hz(84)  # 1046.50 Hz
    e6 = midi_hz(88)  # 1318.51 Hz
    tone = (
        0.62 * np.sin(2.0 * np.pi * c6 * t) * np.exp(-t / 0.36)
        + 0.50 * np.sin(2.0 * np.pi * e6 * t) * np.exp(-t / 0.29)
    )
    tone *= 1.0 - np.exp(-t / 0.0015)  # 1.5 ms attack, no click
    return fade_edges(tone, 0.0008, 0.04)


