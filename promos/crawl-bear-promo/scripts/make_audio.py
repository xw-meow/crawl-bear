def describe(path: Path) -> dict[str, float]:
    """Read a wav back and measure duration / sample rate / channels / levels."""
    with wave.open(str(path), "rb") as handle:
        channels = handle.getnchannels()
        width = handle.getsampwidth()
        rate = handle.getframerate()
        frames = handle.getnframes()
        raw = handle.readframes(frames)
    data = np.frombuffer(raw, dtype=np.int16).astype(np.float64) / 32768.0
    if channels == 2:
        data = data.reshape(-1, 2)
    peak = float(np.max(np.abs(data)))
    rms = float(np.sqrt(np.mean(data**2)))
    return {
        "duration": frames / rate,
        "rate": rate,
        "channels": channels,
        "bit_depth": width * 8,
        "peak_db": amp_to_db(peak),
        "rms_db": amp_to_db(rms),
        "bytes": path.stat().st_size,
    }


def normalise_peak(signal: np.ndarray, target_db: float) -> np.ndarray:
    peak = float(np.max(np.abs(signal)))
    if peak <= 0.0:
        return signal
    return signal * (db_to_amp(target_db) / peak)


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    print("CrawlBear promo audio — synthesizing…\n")

    # --- music bed ------------------------------------------------------
    music_path = OUT_DIR / "music-bed.wav"
    music, stems = build_music()
    write_wav(music_path, music, channels=2)
    print("music-bed.wav")
    for name, stem in stems.items():
        lvl = amp_to_db(float(np.sqrt(np.mean(stem**2))))
        print(f"  stem {name:<7} RMS {lvl:6.1f} dBFS")
    print()

    # --- sound effects ---------------------------------------------------
    sfx_specs = [
        ("pop.wav", "card / sticker pop", make_pop, 60),
        ("click.wav", "button + typing tick", make_click, 40),
        ("stamp.wav", '"已收" rubber stamp', make_stamp, 220),
        ("whoosh.wav", "scene transition swoosh", make_whoosh, 380),
        ("chime.wav", "success bell (C6+E6)", make_chime, 900),
    ]
    for filename, label, factory, expected_ms in sfx_specs:
        signal = normalise_peak(factory(), SFX_PEAK_DB)
        write_wav(OUT_DIR / filename, signal, channels=1)
        produced_ms = 1000.0 * len(signal) / SR
        if abs(produced_ms - expected_ms) > 1.0:
            raise RuntimeError(
                f"{filename}: expected ~{expected_ms} ms, got {produced_ms:.1f} ms"
            )

    # --- verify by reading the files back -------------------------------
    print(f"{'file':<15}{'dur':>8}{'sr':>7}{'ch':>4}{'bit':>5}{'peak':>9}{'rms':>9}{'size':>10}")
    print("-" * 67)
    for filename in (
        "music-bed.wav",
        "pop.wav",
        "click.wav",
        "stamp.wav",
        "whoosh.wav",
        "chime.wav",
    ):
        info = describe(OUT_DIR / filename)
        print(
            f"{filename:<15}{info['duration']:>7.3f}s{int(info['rate']):>7}"
            f"{int(info['channels']):>4}{int(info['bit_depth']):>5}"
            f"{info['peak_db']:>8.1f}dB{info['rms_db']:>8.1f}dB"
            f"{info['bytes'] / 1024:>9.0f}K"
        )

    # --- hard guarantees -------------------------------------------------
    music_info = describe(music_path)
    assert abs(music_info["duration"] - MUSIC_DURATION) < 0.001, "music length drifted"
    assert int(music_info["rate"]) == SR and int(music_info["channels"]) == 2
    assert music_info["peak_db"] <= MUSIC_PEAK_CEILING_DB + 0.05
    assert -20.5 <= music_info["rms_db"] <= -17.5, (
        f"music RMS {music_info['rms_db']:.1f} dBFS is outside the -18..-20 target"
    )
    for filename, *_ in sfx_specs:
        info = describe(OUT_DIR / filename)
        assert info["peak_db"] <= SFX_PEAK_DB + 0.05, f"{filename} too hot"
        assert info["duration"] < 1.0, f"{filename} is not short and clean"
    crest = music_info["peak_db"] - music_info["rms_db"]
    assert 5.0 <= crest <= 18.0, (
        f"unexpected crest factor {crest:.1f} dB (peak {music_info['peak_db']:.1f} / "
        f"RMS {music_info['rms_db']:.1f}) — check the mix balance"
    )

    print("\nAll levels verified. Files written to", OUT_DIR)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
