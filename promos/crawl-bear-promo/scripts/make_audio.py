def marimba_note(
    freq: float,
    velocity: float,
    ring: float | None = None,
) -> np.ndarray:
    """Warm marimba/xylophone pluck: sine fundamental + quiet 4th/10th partials.

    Marimba bars ring with a strong fundamental and much weaker partials near
    4x and 10x the fundamental, which is what gives that wooden, non-synthetic
    "toy instrument" colour. Higher notes decay faster.
    """
    decay = float(np.clip(0.46 * (261.63 / freq) ** 0.30, 0.20, 0.62))
    ring = ring if ring is not None else min(1.6, decay * 6.5)
    n = max(8, int(SR * ring))
    t = np.arange(n) / SR

    body = np.sin(2.0 * np.pi * freq * t)
    body += 0.22 * np.sin(2.0 * np.pi * freq * 4.0 * t) * np.exp(-t / (decay * 0.35))
    body += 0.07 * np.sin(2.0 * np.pi * freq * 9.6 * t) * np.exp(-t / (decay * 0.18))

    env = np.exp(-t / decay)
    attack = 1.0 - np.exp(-t / 0.0022)  # 2 ms mallet attack
    # A whisper of high mallet "tick" keeps the transient from reading as a
    # pure sine beep, without turning into an audible click.
    mallet = 0.018 * np.sin(2.0 * np.pi * 5300.0 * t) * np.exp(-t / 0.0016)
    tone = (body * env + mallet) * attack * velocity
    return tone


def pad_note(freq: float, duration: float, amp: float) -> np.ndarray:
    """Very quiet bass pad: sine + 2nd harmonic, slow 0.8 s attack."""
    n = int(SR * duration)
    t = np.arange(n) / SR
    attack = 1.0 - np.exp(-t / 0.30)  # ~93% at 0.8 s => slow, pillow-soft entry
    release_start = max(0.0, duration - 0.55)
    release = np.ones(n)
    mask = t > release_start
    release[mask] = np.exp(-(t[mask] - release_start) / 0.24)
    env = attack * release
    wave_ = np.sin(2.0 * np.pi * freq * t) + 0.22 * np.sin(2.0 * np.pi * 2.0 * freq * t)
    return wave_ * env * amp


def shaker_hit(rng: np.random.Generator, amp: float) -> np.ndarray:
    """Tiny filtered-noise shaker: high-passed noise with a 16 ms decay."""
    n = int(SR * 0.085)
    t = np.arange(n) / SR
    noise = rng.standard_normal(n)
    # Keep only the airy top end; anything below ~4 kHz would fight the plucks.
    noise = highpass(noise, 4200.0)
    env = (1.0 - np.exp(-t / 0.0009)) * np.exp(-t / 0.016)
    fades = np.exp(-t / 0.028)
    return noise * env * fades * amp


