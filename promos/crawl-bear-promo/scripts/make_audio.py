#!/usr/bin/env python3
"""CrawlBear promo film — soundtrack + UI sound effects, synthesized from scratch.

Everything here is generated by numpy (no samples, no external libraries beyond
numpy). The script is deterministic (fixed RNG seeds) and idempotent: running it
again overwrites the same files with byte-identical audio.

Run with the DSH runtime Python (numpy lives there):

    /Users/dengwei.daviant/.dsh/dsh-runtimes/dsh-primary-runtime/dependencies/python/bin/python3 \
        promo/scripts/make_audio.py

Outputs (promo/public/audio/):

  music-bed.wav   54.0 s · 44.1 kHz · stereo · 16-bit
                  Warm "journal / marimba" bed at 96 BPM. C major pentatonic,
                  4/4, one chord per bar, loop C – G/B – Am – F. Marimba
                  eighth-note arpeggios (root / fifth / octave / third) with
                  humanised velocity + timing, a very quiet sine+2nd-harmonic
                  bass pad (0.8 s attack) and barely-there filtered-noise
                  shaker eighths. Bars 4–8 get a gentle 1.4 s lift. The last
                  2 s fade out so the film can end on the outro.
                  Mix target: peak <= -3 dBFS, RMS ~ -19 dBFS.

  pop.wav      60 ms   card / sticker pop        (results grid, hook chips)
  click.wav    40 ms   button + typing tick      (paste typing, CTA)
  stamp.wav   220 ms   "已收" rubber stamp thump  (collect stamps, outro logo)
  whoosh.wav  380 ms   scene transition swoosh   (paper slide + sticker slam)
  chime.wav   900 ms   success bell C6+E6        (crawl done, privacy payoff)

All effects are mono 44.1 kHz 16-bit and peak-normalised to -6 dBFS so they sit
under the music without ever clipping.

Sound design notes:
- No scipy is available, so filters are hand-rolled (FFT band shaping for static
  filters, a TPT state-variable filter for the whoosh sweep).
- Humanised timing (jitter + light swing) and varied velocities are what keep
  the eighth-note bed from feeling like a metronome.
"""

from __future__ import annotations

import math
import random
import wave
from pathlib import Path

import numpy as np

# ---------------------------------------------------------------------------
# Global config
# ---------------------------------------------------------------------------

SR = 44100
ROOT = Path(__file__).resolve().parent.parent  # -> promo/
OUT_DIR = ROOT / "public" / "audio"

MUSIC_DURATION = 54.0  # exactly the film length (1620 frames @ 30 fps)
BPM = 96.0
BEAT = 60.0 / BPM  # 0.625 s
BAR = 4.0 * BEAT  # 2.5 s
EIGHTH = BEAT / 2.0  # 0.3125 s

MUSIC_PEAK_CEILING_DB = -3.0
MUSIC_RMS_TARGET_DB = -19.0
SFX_PEAK_DB = -6.0

# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------


def db_to_amp(db: float) -> float:
    return 10.0 ** (db / 20.0)


def amp_to_db(x: float) -> float:
    return 20.0 * math.log10(max(x, 1e-12))


def midi_hz(midi: int) -> float:
    return 440.0 * 2.0 ** ((midi - 69) / 12.0)


def smoothstep(x: np.ndarray) -> np.ndarray:
    """0..1 clamped smoothstep."""
    x = np.clip(x, 0.0, 1.0)
    return x * x * (3.0 - 2.0 * x)


def fade_edges(buf: np.ndarray, in_s: float, out_s: float) -> np.ndarray:
    """Fade a (channels, n) or (n,) buffer in/out with smoothstep shapes."""
    n = buf.shape[-1]
    n_in = min(int(SR * in_s), n)
    n_out = min(int(SR * out_s), n)
    if n_in > 1:
        ramp = smoothstep(np.linspace(0.0, 1.0, n_in))
        buf[..., :n_in] *= ramp
    if n_out > 1:
        ramp = smoothstep(np.linspace(1.0, 0.0, n_out))
        buf[..., n - n_out :] *= ramp
    return buf


def fft_shape(x: np.ndarray, gain_of_freq) -> np.ndarray:
    """Multiply a signal's spectrum by an arbitrary frequency response."""
    n = len(x)
    spec = np.fft.rfft(x)
    freqs = np.fft.rfftfreq(n, 1.0 / SR)
    return np.fft.irfft(spec * gain_of_freq(freqs), n)


def lowpass(x: np.ndarray, cutoff: float, slope: float = 1.4) -> np.ndarray:
    hi = min(cutoff * slope, SR / 2.0)

    def response(freqs: np.ndarray) -> np.ndarray:
        g = np.ones_like(freqs)
        mask = freqs > cutoff
        g[mask] = np.clip((hi - freqs[mask]) / (hi - cutoff), 0.0, 1.0)
        return g

    return fft_shape(x, response)


def highpass(x: np.ndarray, cutoff: float, slope: float = 1.35) -> np.ndarray:
    lo = max(cutoff / slope, 1.0)

    def response(freqs: np.ndarray) -> np.ndarray:
        g = np.ones_like(freqs)
        mask = freqs < cutoff
        g[mask] = np.clip((freqs[mask] - lo) / (cutoff - lo), 0.0, 1.0)
        return g

    return fft_shape(x, response)


def pan_gains(pan: float) -> tuple[float, float]:
    """Constant-power pan, pan in [-1, 1] (0 = centre)."""
    theta = (max(-1.0, min(1.0, pan)) + 1.0) * math.pi / 4.0
    return math.cos(theta), math.sin(theta)


def add_into(
    bus: np.ndarray,
    signal: np.ndarray,
    start_s: float,
    pan: float,
    gain: float = 1.0,
) -> None:
    """Mix a mono signal into a (2, n) stereo bus at start_s seconds."""
    if len(signal) == 0 or gain == 0.0:
        return
    # Humanised timings can land a few ms before t=0; clamp instead of slicing
    # with a negative index (which silently produces empty slices in numpy).
    start = max(0, int(round(start_s * SR)))
    if start >= bus.shape[1]:
        return
    signal = signal * gain
    end = min(bus.shape[1], start + len(signal))
    seg = signal[: end - start]
    gl, gr = pan_gains(pan)
    bus[0, start:end] += seg * gl
    bus[1, start:end] += seg * gr


def write_wav(path: Path, data: np.ndarray, channels: int) -> None:
    """Write float data in [-1, 1] as 16-bit PCM."""
    clipped = np.clip(data, -1.0, 1.0)
    if channels == 1:
        pcm = np.round(clipped * 32767.0).astype(np.int16)
    else:
        pcm = np.round(clipped.T * 32767.0).astype(np.int16)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(channels)
        handle.setsampwidth(2)
        handle.setframerate(SR)
        handle.writeframes(pcm.tobytes())


